const tmp = (p: string) => fs.mkdtemp(path.join(os.tmpdir(), `lattice-${p}-`));
async function write(file: string, body = 'x') {
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, body);
}
function env(home: string): DetectEnv {
  return {
    home,
    appData: path.join(home, 'Roaming'),
    localAppData: path.join(home, 'Local'),
    programData: path.join(home, 'ProgramData'),
    programFiles: [],
    drives: [],
    steamLibraries: async () => [],
    gogPaths: async () => [],
  };
}

describe('names other managers use', () => {
  it('reads Nexus ids from Vortex folder and archive names', () => {
    expect(parseNexusArchiveName('Cyber Engine Tweaks-107-1-38-1-1735000000')).toEqual({ title: 'Cyber Engine Tweaks', modId: 107, version: '1.38.1', uploaded: 1735000000 });
    expect(parseNexusArchiveName('SkyUI_5_2_SE-12604-5-2SE-1573409487.1')).toMatchObject({ modId: 12604, version: '5.2SE' });
    expect(parseNexusArchiveName('My own mod')).toBeNull();
    expect(defForName('Skyrim Special Edition')?.id).toBe('skyrimse');
    expect(defForName('LethalCompany')?.id).toBe('lethal-company');
    expect(defForName('RiskOfRain2')?.id).toBe('riskofrain2');
  });
});

describe('Vortex', () => {
  it('finds the staging folder through the deployment manifest, with what is deployed and where', async () => {
    const home = await tmp('vx');
    const game = path.join(home, 'Valheim');
    const staging = path.join(home, 'VortexMods', 'valheim');
    await write(path.join(staging, 'Jotunn-1138-2-20-0-1700000000', 'Jotunn.dll'));
    await write(path.join(staging, 'Not deployed', 'Other.dll'));
    await write(path.join(staging, '__folder_managed_by_vortex'), '');
    const plugins = path.join(game, 'BepInEx', 'plugins');
    await write(path.join(plugins, 'Jotunn.dll'));
    await write(
      path.join(plugins, 'vortex.deployment.json'),
      JSON.stringify({ version: 1, instance: 'x', stagingPath: staging, targetPath: plugins, files: [{ relPath: 'Jotunn.dll', source: 'Jotunn-1138-2-20-0-1700000000', time: 1 }] }),
    );
    const [src] = await vortexSources(env(home), [{ defId: 'valheim', path: game }]);
    expect(src).toMatchObject({ manager: 'vortex', defId: 'valheim', deployedFiles: 1 });
    expect(src.profiles.map((p) => p.id)).toEqual(['deployed', 'all']);
    const deployed = src.profiles[0].mods;
    expect(deployed).toHaveLength(1);
    expect(deployed[0]).toMatchObject({ name: 'Jotunn', prefix: 'BepInEx/plugins', nexus: { modId: 1138, version: '2.20.0', uploaded: 1700000000 } });
    // a mod Vortex has not deployed goes where its other mods go
    expect(src.profiles[1].mods.find((m) => m.name === 'Not deployed')).toMatchObject({ prefix: 'BepInEx/plugins', enabled: true });
    expect(await vortexDeployedFiles(game, gameDef('valheim')!)).toBe(1);
  });
});

describe('Mod Organizer 2', () => {
  it('reads instances, Nexus ids from meta.ini and priorities from modlist.txt', async () => {
    const home = await tmp('mo2');
    const inst = path.join(home, 'Local', 'ModOrganizer', 'Skyrim SE');
    await write(path.join(inst, 'ModOrganizer.ini'), `[General]\ngameName=Skyrim Special Edition\nselected_profile=@ByteArray(Default)\n[Settings]\n`);
    await write(path.join(inst, 'mods', 'SkyUI', 'SkyUI_SE.esp'));
    await write(path.join(inst, 'mods', 'SkyUI', 'meta.ini'), `[General]\nmodid=12604\nversion=5.2SE\n[installedFiles]\nsize=1\n1\\modid=12604\n1\\fileid=35407\n`);
    await write(path.join(inst, 'mods', 'SKSE', 'Root', 'skse64_loader.exe'));
    await write(path.join(inst, 'mods', 'Patch', 'patch.esp'));
    await write(path.join(inst, 'profiles', 'Default', 'modlist.txt'), `# This file was automatically generated by Mod Organizer.\n+Patch\n-Old\n+UI_separator\n+SkyUI\n+SKSE\n`);
    const [src] = await mo2Sources(env(home));
    expect(src).toMatchObject({ manager: 'mo2', defId: 'skyrimse' });
    const mods = src.profiles[0].mods;
    expect(mods.map((m) => m.name)).toEqual(['Patch', 'Old', 'SkyUI', 'SKSE']);
    expect(mods.find((m) => m.name === 'SkyUI')).toMatchObject({ enabled: true, nexus: { modId: 12604, fileId: 35407, version: '5.2SE' } });
    expect(mods.find((m) => m.name === 'Old')?.enabled).toBe(false);
    expect(mods.find((m) => m.name === 'SKSE')?.problem).toBe('root');
    // the first line of modlist.txt wins
    expect(mods[0].priority).toBeGreaterThan(mods[2].priority);
  });
});

